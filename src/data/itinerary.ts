function items(list: I[]): DayItem[] {
  return list.map(([text, o = {}]) => ({
    text,
    time: o.t,
    attractionId: o.a,
    kind: o.k ?? (o.a ? 'visita' : 'logistica'),
    reliability: o.r ?? 'planejado',
    note: o.n,
  }))
}

